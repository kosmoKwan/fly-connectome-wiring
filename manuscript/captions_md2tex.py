"""Convert the figure legends in figures_v3/Claude_v8第三轮_20260930/captions_draft.md to LaTeX.

The legends (and every number in them) are generated by the figure scripts; this converter changes typography only
(Markdown bold -> \\textbf, Unicode symbols and the few formulas in MATH -> LaTeX, panel letters in bold) plus the short,
explicit list of wording changes in WORDING below, which align phrases with the manuscript and never change a number.
Nature Communications has no Extended Data, so the label "Extended Data Fig." becomes "Supplementary Fig." (LABELS below).
Rerun it whenever `bash src/run_all.sh` in the figure folder regenerates the legends.

usage: python captions_md2tex.py  (paths are relative to this file)
writes ../generated/captions.tex with \\capTitleA..F / \\capBodyA..F (Fig. 1-6) and \\capTitleEDA..G / \\capBodyEDA..G
(Extended Data Fig. 1-7 of the figure folder = Supplementary Fig. 1-7 here)
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIGDIR = "Claude_v8第三轮_20260930"
SRC = HERE.parents[1] / "figures_v3" / FIGDIR / "captions_draft.md"
OUT = HERE.parent / "generated" / "captions.tex"
N_MAIN, N_ED = 6, 7

# Wording aligned with the manuscript (each entry must match exactly once). Empty again since 2026-09-30 (evening): the figure
# session adopted at source the six changes made here for v9_NC (no claim of robustness to transmitter signs; Supplementary Fig. 2c
# p values in the order of the families named; Supplementary Fig. 2b 'about as rhythmic'; Fig. 5 title = section heading;
# Supplementary Fig. 5 title 'at most partially').
WORDING = {}

# Figure labels in the legends: NC has no Extended Data; those figures are Supplementary Figures here.
LABELS = {"Extended Data Fig.": "Supplementary Fig."}

# Formulas typeset as in the manuscript (matched before any escaping).
MATH = {
    "y\u00b1 = (e \u00b1 f)/\u221a2": r"$y_\pm=(e\pm f)/\sqrt2$",
    "D = Var(y\u2212)/[Var(y+) + Var(y\u2212)]": r"$D=\mathrm{Var}(y_-)/[\mathrm{Var}(y_+)+\mathrm{Var}(y_-)]$",
    "Var(y+)": r"$\mathrm{Var}(y_+)$",
    "f_opp": r"$f_{\mathrm{opp}}$",
    "RF = (S_arm \u2212 S_parent)/(S_real \u2212 S_parent)": r"$\mathrm{RF}=(S_{\mathrm{arm}}-S_{\mathrm{parent}})/(S_{\mathrm{real}}-S_{\mathrm{parent}})$",
    "f(x) = min(max(x, 0), 1)": r"$f(x)=\min(\max(x,0),1)$",
}

UNI = {
    "\u2013": "--", "\u2014": "---", "\u2212": "$-$", "\u00d7": "$\\times$", "\u00b1": "$\\pm$",
    "\u2265": "$\\geq$", "\u2264": "$\\leq$", "\u03c1": "$\\rho$", "\u03b2": "$\\beta$", "\u03be": "$\\xi$",
    "\u03b3": "$\\gamma$", "\u00b5": "$\\mu$", "\u2248": "$\\approx$", "\u2192": "$\\rightarrow$", "\u00a0": "~",
}


def to_tex(s: str) -> str:
    keep = []
    for k, v in MATH.items():
        if k in s:
            keep.append(v)
            s = s.replace(k, f"@@M{len(keep) - 1}@@")
    s = s.replace("\\", "\\textbackslash{}")
    for ch in "%&#":
        s = s.replace(ch, "\\" + ch)
    s = re.sub(r"\bX_(lo|hi)\b", "XARM\\1", s)                       # arm names X_lo, X_hi (typeset below)
    s = s.replace("_", "\\_")
    s = re.sub(r"(^|(?<=[\s(\[]))'(?=\w)", r"\1`", s)                # opening quote; apostrophes untouched
    for k, v in UNI.items():
        s = s.replace(k, v)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\\textit{\1}", s)
    # panel labels at the start of the body or of a sentence: "a," "b,c," "d--g,"
    s = re.sub(r"(^|(?<=\.\s))([a-i](?:(?:,|--)[a-i])*),\s", lambda m: m.group(1) + "\\textbf{" + m.group(2) + "}, ", s)
    s = re.sub(r"XARM(lo|hi)", r"X$_{\\mathrm{\1}}$", s)
    for i, v in enumerate(keep):
        s = s.replace(f"@@M{i}@@", v)
    left = [c for c in s if ord(c) > 127]
    if left:
        raise SystemExit(f"unmapped non-ASCII characters: {sorted(set(left))}")
    return s


def main():
    text = SRC.read_text(encoding="utf-8")
    for old, new in WORDING.items():
        if text.count(old) != 1:
            raise SystemExit(f"wording change does not match exactly once: {old!r}")
        text = text.replace(old, new)
    blocks = re.findall(r"\*\*((?:Extended Data )?Fig\. \d) \| (.+?)\*\*\s+(.+?)(?=\n\s*\n\*\*(?:Extended Data )?Fig\. |\Z)",
                        text, flags=re.S)
    names = [b[0] for b in blocks]
    want = [f"Fig. {i}" for i in range(1, N_MAIN + 1)] + [f"Extended Data Fig. {i}" for i in range(1, N_ED + 1)]
    if names != want:
        raise SystemExit(f"expected legends {want}, found {names}")
    lines = [f"% Generated by src/captions_md2tex.py from figures_v3/{FIGDIR}/captions_draft.md -- do not edit by hand."]
    for name, title, body in blocks:
        key = ("ED" if name.startswith("Extended") else "") + "ABCDEFG"[int(name.split()[-1]) - 1]
        title, body = title.strip(), " ".join(body.split())
        for old, new in LABELS.items():
            title, body = title.replace(old, new), body.replace(old, new)
        lines.append(f"\\newcommand{{\\capTitle{key}}}{{{to_tex(title)}}}")
        lines.append(f"\\newcommand{{\\capBody{key}}}{{{to_tex(body)}}}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(blocks)} legends, {len(WORDING)} wording changes, labels {LABELS})")


if __name__ == "__main__":
    main()
