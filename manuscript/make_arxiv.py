"""Build the arXiv replacement package (v2 of the arXiv posting of v8_NC) from the v9_NC English manuscript (run after src/build.sh).

arXiv does not accept PDFs produced from LaTeX; it compiles the uploaded source itself (pdfLaTeX, TeX Live). This script
writes a self-contained, ASCII-only source folder ../arxiv/ and zips it to <experiment root>/paper_最新版/:
  main.tex             manuscript.tex with \\graphicspath pointing to figures/, no line numbers, no non-ASCII comments
  generated/*.tex      legends and Supplementary Tables (generated by the build)
  figures/*.pdf        the thirteen figure files referenced by the manuscript
It also writes the plain-text title, authors, abstract and comments for the arXiv form. The manuscript itself is not
changed. The package is test-compiled here with tectonic (XeTeX); arXiv will compile it with pdfLaTeX.

usage: python make_arxiv.py
"""
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

V = Path(__file__).resolve().parent.parent
FIGDIR = "Claude_v8第三轮_20260930"
FIG = V.parent / "figures_v3" / FIGDIR
A = V / "arxiv"
OUT = V.parents[1] / "paper_最新版"
N_FIGS = 13

tex = (V / "manuscript.tex").read_text(encoding="utf-8")
old_gp = r"\graphicspath{{../figures_v3/" + FIGDIR + "/}}"
if tex.count(old_gp) != 1:
    raise SystemExit("graphicspath not found exactly once")
tex = tex.replace(old_gp, r"\graphicspath{{figures/}}")
if tex.count("\\linenumbers\n") != 1:
    raise SystemExit("\\linenumbers not found exactly once")
tex = tex.replace("\\linenumbers\n", "")                                  # a preprint is read without line numbers
# As for the first arXiv version (v8_NC): the public version carries no pending placeholders. Statements that need every
# author's confirmation (funding, contributions, competing interests) are left out, and the data/code statements keep only
# the commitment to a public deposit, without the NC-review wording.
CLEAN = [
    (r" will be deposited in a public repository \pending{link to be added}.", r" will be deposited in a public repository upon publication."),
    (r"The code is available to editors and reviewers upon request and will be deposited in a DOI-minting repository (Zenodo) upon publication.",
     r"The code will be deposited in a DOI-minting repository (Zenodo) upon publication."),
]
for old, new in CLEAN:
    if tex.count(old) != 1:
        raise SystemExit(f"arXiv clean-up: expected one match for {old[:60]!r}")
    tex = tex.replace(old, new)
for sec in ("Acknowledgements", "Author contributions", "Competing interests"):
    m = re.search(r"\\section\*\{" + sec + r"\}\n.*?\n(?=\n)", tex, flags=re.S)
    if not m or "\\pending{" not in m.group(0):
        raise SystemExit(f"arXiv clean-up: section {sec} not found or not pending")
    tex = tex.replace(m.group(0) + "\n", "", 1)
if "\\pending{" in tex:
    raise SystemExit("arXiv clean-up: a pending placeholder is left")
lines = [l for l in tex.splitlines(keepends=True) if not (l.lstrip().startswith("%") and any(ord(c) > 127 for c in l))]
tex = "% arXiv source of the v9_NC manuscript, generated by src/make_arxiv.py; compile with pdfLaTeX (no bibtex needed).\n" + "".join(lines)
if any(ord(c) > 127 for c in tex):
    raise SystemExit(f"non-ASCII left in main.tex: {sorted({c for c in tex if ord(c) > 127})}")

figs = sorted(set(re.findall(r"\\(?:mainfig|figpage\{[^}]*\})\{([^}]+\.pdf)\}", tex)))
if len(figs) != N_FIGS:
    raise SystemExit(f"expected {N_FIGS} figure files, found {figs}")

if A.exists():
    shutil.rmtree(A)
(A / "figures").mkdir(parents=True)
(A / "generated").mkdir()
(A / "main.tex").write_text(tex, encoding="ascii")
for f in figs:
    shutil.copy2(FIG / f, A / "figures" / f)
for f in ("captions.tex", "si_tables.tex"):
    g = "".join(l for l in (V / "generated" / f).read_text(encoding="utf-8").splitlines(keepends=True)
                if not (l.lstrip().startswith("%") and any(ord(c) > 127 for c in l)))
    if any(ord(c) > 127 for c in g):
        raise SystemExit(f"non-ASCII in generated/{f}")
    (A / "generated" / f).write_text(g, encoding="ascii")

# test compile in a scratch copy, so that the package holds sources only
tmp = V / "arxiv_testbuild"
if tmp.exists():
    shutil.rmtree(tmp)
shutil.copytree(A, tmp)
r = subprocess.run(["tectonic", "-X", "compile", "main.tex"], cwd=tmp, capture_output=True, text=True)
if r.returncode != 0:
    raise SystemExit("test compile failed:\n" + r.stderr[-3000:])
import pymupdf                                                                 # page count of the test build
pages = len(pymupdf.open(tmp / "main.pdf"))
n_tab = len(re.findall(r"\\begin\{table\}", (A / "generated" / "si_tables.tex").read_text()))
n_main = len(re.findall(r"\\mainfig\{", tex)); n_si = len(re.findall(r"\\figpage\{", tex))

OUT.mkdir(exist_ok=True)
zpath = OUT / "arXiv上传包_果蝇连接组论文_v9.zip"
with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
    for p in sorted(A.rglob("*")):
        if p.is_file():
            z.write(p, p.relative_to(A).as_posix())

# plain text for the arXiv form (title, authors, abstract without LaTeX)
title = re.search(r"\\title\{\\textbf\{(.*?)\}\}", tex).group(1)
auth = re.search(r"\\author\{(.*?)\\\\\[4pt\]", tex, flags=re.S).group(1)
authors = re.sub(r"\$\^\{[^}]*\}\$", "", auth).replace(" and ", ", ")
abs_tex = re.search(r"\\begin\{abstract\}\s*\\noindent\s*(.*?)\s*\\end\{abstract\}", tex, flags=re.S).group(1)
abstract = abs_tex.replace("---", "\u2014").replace("--", "\u2013")
abstract = re.sub(r"\\textit\{([^}]*)\}", r"\1", abstract)
abstract = re.sub(r"\s+", " ", abstract).strip()
if "\\" in abstract or "{" in abstract:
    raise SystemExit(f"LaTeX left in the abstract: {abstract}")
comments = (f"{pages} pages, {n_main} figures; Supplementary Information with {n_si} figures and {n_tab} tables. "
            "v2: adds pre-registered robustness and mechanism analyses (second neuron nonlinearity, competitive rewired ensembles, "
            "transmitter-sign perturbations, capped input reassignment, common and differential activity, final-layer rescue)")
(OUT / "arXiv填表内容_v9.txt").write_text(
    "This is a REPLACEMENT (v2) of the arXiv posting made from v8: on the arXiv user page, choose 'Replace' for that article\n"
    "and upload arXiv上传包_果蝇连接组论文_v9.zip. Category and license stay as in v1.\n\n"
    f"Title:\n{title}\n\nAuthors:\n{authors}\n\nAbstract ({len(abstract)} characters; arXiv limit 1,920):\n{abstract}\n\n"
    "Primary category:\ncs.NE (Neural and Evolutionary Computing) -- unchanged from v1\n\n"
    "Cross-list:\nq-bio.NC (Neurons and Cognition)\n\n"
    "License:\narXiv.org perpetual, non-exclusive license (unchanged from v1)\n\n"
    f"Comments:\n{comments}\n\n"
    "Journal-ref, DOI, Report number, MSC/ACM classes:\n(leave empty)\n", encoding="utf-8")
print(f"wrote {A.relative_to(V.parent)} ({len(figs)} figures), test compile OK ({pages} pages; {n_main} + {n_si} figures, {n_tab} tables), "
      f"{zpath.name}, arXiv填表内容_v9.txt")
